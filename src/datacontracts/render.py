"""Generated reports and exports. Output is deterministic so CI can check it is current."""

from __future__ import annotations

from datacontracts import export, lineage, rules
from datacontracts.compat import CHANGE_KINDS, Change
from datacontracts.lineage import Impact
from datacontracts.model import Contract, Registry

BANNER = "<!-- Generated by `dcr report`. Do not edit; change the contracts and regenerate. -->\n\n"


def _row(*cells: object) -> str:
    return "| " + " | ".join(str(c).replace("|", "\\|") for c in cells) + " |\n"


def _node(cid: str) -> str:
    return cid.replace(".", "_")


def catalog(reg: Registry) -> str:
    out = [BANNER, f"# Contract catalogue: {reg.name}\n\n"]
    cs = sorted(reg.contracts.values(), key=lambda c: c.id)
    by_status: dict[str, int] = {}
    for c in cs:
        by_status[c.status] = by_status.get(c.status, 0) + 1
    out.append(
        f"{len(cs)} contracts: "
        + ", ".join(f"{n} {s}" for s, n in sorted(by_status.items()))
        + ".\n\n"
    )
    out.append(
        _row(
            "Contract",
            "Version",
            "Status",
            "Tier",
            "Owner",
            "Classification",
            "Fields",
            "Personal data",
            "Consumers",
            "Upstream",
        )
    )
    out.append(_row(*["---"] * 10))
    for c in cs:
        pii = sum(1 for f in c.fields if f.pii)
        out.append(
            _row(
                f"`{c.id}`",
                c.version,
                c.status,
                c.tier,
                c.owner,
                c.classification,
                len(c.fields),
                pii or "none",
                len(c.consumers),
                ", ".join(f"`{u}`" for u in c.upstream) or "none",
            )
        )
    out.append(
        "\nTier 1 is critical, 2 important, 3 standard. Personal data counts fields marked `pii`.\n"
    )
    return "".join(out)


def lineage_report(reg: Registry) -> str:
    out = [
        BANNER,
        "# Lineage\n\nArrows point from a source contract to the contract built from it.\n\n```mermaid\nflowchart LR\n",
    ]
    for c in sorted(reg.contracts.values(), key=lambda c: c.id):
        out.append(f'  {_node(c.id)}["{c.id}<br/>v{c.version}"]\n')
    for c in sorted(reg.contracts.values(), key=lambda c: c.id):
        for up in sorted(c.upstream):
            if up in reg.contracts:
                out.append(f"  {_node(up)} --> {_node(c.id)}\n")
    out.append("```\n\n## What each contract reaches\n\n")
    out.append(
        _row(
            "Contract",
            "Built directly from it",
            "Everything downstream",
            "Consumers affected by a change to the whole contract",
        )
    )
    out.append(_row("---", "---", "---", "---"))
    dm = lineage.downstream_map(reg)
    for c in sorted(reg.contracts.values(), key=lambda c: c.id):
        closure = lineage.downstream_closure(reg, c.id)
        consumers = {cons.id for cons in c.consumers}
        for d in closure:
            consumers |= {cons.id for cons in reg.contracts[d].consumers}
        out.append(
            _row(
                f"`{c.id}`",
                ", ".join(f"`{d}`" for d in dm[c.id]) or "none",
                len(closure),
                len(consumers),
            )
        )
    return "".join(out)


def field_usage(reg: Registry) -> str:
    out = [
        BANNER,
        "# Field usage\n\nWho reads each field. A field nobody reads is a candidate for deprecation; a field many read is expensive to change.\n",
    ]
    for c in sorted(reg.contracts.values(), key=lambda c: c.id):
        out.append(f"\n## `{c.id}` {c.version}\n\n")
        out.append(_row("Field", "Type", "Readers", "Notes"))
        out.append(_row("---", "---", "---", "---"))
        deprecated = {d.field: d for d in c.deprecations}
        for f in c.fields:
            readers = [cons.id for cons in c.consumers if f.name in cons.fields]
            notes = []
            if f.primary_key:
                notes.append("key")
            if f.pii:
                notes.append("personal data")
            if f.name in deprecated:
                notes.append(f"deprecated, sunset {deprecated[f.name].sunset}")
            if not readers and not f.primary_key and c.status == "active":
                notes.append("no registered reader")
            out.append(_row(f"`{f.name}`", f.type, ", ".join(readers) or "none", "; ".join(notes)))
    return "".join(out)


def pii_register(reg: Registry) -> str:
    out = [
        BANNER,
        "# Personal data register\n\nEvery field marked `pii`, where it flows and who reads it.\n\n",
    ]
    out.append(
        _row("Contract", "Field", "Classification", "Retention (days)", "Read by", "Flows into")
    )
    out.append(_row(*["---"] * 6))
    rows = 0
    for c in sorted(reg.contracts.values(), key=lambda c: c.id):
        for f in c.fields:
            if not f.pii:
                continue
            readers = [cons.id for cons in c.consumers if f.name in cons.fields]
            flows = [
                f"{d.id}.{g.name}"
                for d in sorted(reg.contracts.values(), key=lambda x: x.id)
                for g in d.fields
                if g.derived_from == f"{c.id}.{f.name}"
            ]
            out.append(
                _row(
                    f"`{c.id}`",
                    f"`{f.name}`",
                    c.classification,
                    c.retention_days or "not set",
                    ", ".join(readers) or "none",
                    ", ".join(f"`{x}`" for x in flows) or "none",
                )
            )
            rows += 1
    out.append(f"\n{rows} personal data fields in {len(reg.contracts)} contracts.\n")
    return "".join(out)


def rules_report() -> str:
    out = [
        BANNER,
        "# Policy rules\n\nEvery rule runs on every `dcr check`. A rule has an ID, a severity and a failing-case test.\n\n",
    ]
    out.append(_row("Rule", "Severity", "Checks", "Why it matters"))
    out.append(_row("---", "---", "---", "---"))
    for rid, sev, title, why in rules.catalog():
        out.append(_row(rid, sev, title, why))
    return "".join(out)


def change_kinds() -> str:
    out = [
        BANNER,
        "# Compatibility rules\n\nEvery kind of change `dcr compat` can report, judged from the point of view of a consumer that already reads the data. ",
        "The required version bump is the highest level among the changes: breaking needs a major, minor a minor, patch a patch.\n\n",
    ]
    out.append(_row("Change", "Level", "Why"))
    out.append(_row("---", "---", "---"))
    for kind, (levels, why) in CHANGE_KINDS.items():
        out.append(_row(f"`{kind}`", " or ".join(levels), why))
    return "".join(out)


def all_reports(reg: Registry) -> dict[str, str]:
    return {
        "reports/catalog.md": catalog(reg),
        "reports/lineage.md": lineage_report(reg),
        "reports/field-usage.md": field_usage(reg),
        "reports/pii-register.md": pii_register(reg),
        "reports/rules.md": rules_report(),
        "reports/change-kinds.md": change_kinds(),
    }


def all_exports(reg: Registry) -> dict[str, str]:
    out: dict[str, str] = {}
    for c in sorted(reg.contracts.values(), key=lambda c: c.id):
        out[f"schemas/{c.id}.schema.json"] = export.json_schema(c)
        out[f"ddl/ansi/{c.id}.sql"] = export.ddl(c, "ansi")
        out[f"ddl/spark/{c.id}.sql"] = export.ddl(c, "spark")
    return out


def findings_markdown(reg: Registry, findings: list[rules.Finding], n_rules: int) -> str:
    out = [
        f"## Registry check\n\n{len(reg.contracts)} contracts, {n_rules} rules: **{len(findings)} findings**.\n\n"
    ]
    if findings:
        out.append(_row("Severity", "Rule", "Subject", "Message"))
        out.append(_row("---", "---", "---", "---"))
        for f in findings:
            out.append(_row(f.severity, f.rule, f"`{f.subject}`", f.message))
    return "".join(out)


def compat_text(
    head: Contract, base_version: str, changes: list[Change], needed: str, impacts: list[Impact]
) -> str:
    out = [f"{head.id}: {base_version} -> {head.version}, needs a {needed} bump\n"]
    for c in changes:
        target = f" `{c.subject}`" if c.subject else ""
        planned = " (planned removal)" if c.planned else ""
        out.append(f"  {c.level:8} {c.kind}{target}: {c.detail}{planned}\n")
    breaking = [c for c in changes if c.level == "breaking"]
    if breaking and impacts:
        out.append("  reaches:\n")
        for i in impacts:
            out.append(f"    {i.criticality:6} {i.consumer} ({i.team}) {i.via}\n")
    elif breaking:
        out.append("  reaches: no registered consumer reads the changed fields\n")
    return "".join(out)
