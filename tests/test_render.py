def test_every_report_is_deterministic_and_marked_generated() -> None:
    reg = load(ROOT)
    first, second = all_reports(reg), all_reports(reg)
    assert first == second
    assert set(first) == {
        "reports/catalog.md",
        "reports/lineage.md",
        "reports/field-usage.md",
        "reports/pii-register.md",
        "reports/rules.md",
        "reports/change-kinds.md",
    }
    assert all(text.startswith("<!-- Generated by `dcr report`.") for text in first.values())


