def test_findings_markdown_with_and_without_findings(sample: Path) -> None:
    reg = load(sample)
    assert findings_markdown(reg, [], 17).strip().endswith("**0 findings**.")
    edit(sample, "contracts/sales.orders.toml", 'owner = "sales-data"', 'owner = "a|b"')
    reg = load(sample)
    text = findings_markdown(reg, rules.run(reg, TODAY), 17)
    assert "| high | DC003 | `sales.orders` |" in text
    assert "a\\|b" in text  # pipes in a cell are escaped


def test_compat_text_variants() -> None:
    reg = load(ROOT)
    head = reg.contracts["sales.orders"]
    ch = [
        compat.Change("field-removed", "breaking", "amount", "gone", planned=True),
        compat.Change("field-added", "minor", "x", "new"),
    ]
    impacts = lineage.impact(reg, head, ch[:1])
    text = compat_text(head, "1.1.0", ch, "major", impacts)
    assert text.startswith("sales.orders: 1.1.0 -> 1.2.0, needs a major bump\n")
    assert "  breaking field-removed `amount`: gone (planned removal)\n" in text
    assert "  minor    field-added `x`: new\n" in text
    assert "    high   finance.revenue-pipeline (finance-data) direct\n" in text
    assert "no registered consumer reads" in compat_text(head, "1.1.0", ch, "major", [])
    assert "reaches" not in compat_text(head, "1.1.0", ch[1:], "minor", [])
    whole = compat.Change("sla-freshness-weakened", "breaking", "", "worse")
    assert "`" not in compat_text(head, "1.1.0", [whole], "major", [])


